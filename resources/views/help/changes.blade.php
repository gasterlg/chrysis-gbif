<p>A list of every change applied to our data from this tool (mostly accepted GBIF matches), with what the value was before and after.</p>
<h3>Undoing a mistake</h3>
<ol>
    <li>Find the change (search by species or filter by date).</li>
    <li>Compare <strong>before</strong> and <strong>after</strong>.</li>
    <li>Press <strong>Roll back</strong> and confirm. The old value is restored and the rollback itself is recorded.</li>
</ol>
<p><em>A rollback is refused if the same species was changed again afterwards – undo the newer change first.</em></p>
