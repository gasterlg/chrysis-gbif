<p>The accounts that can log in. These are the same accounts as the old chrysis.net /admin. Only Admins see this page.</p>
<h3>Roles and permissions</h3>
<ul>
    <li><strong>Admin</strong>: everything, including this page and the login audit.</li>
    <li><strong>SuperUser</strong>: can browse species, datasets and exports.</li>
    <li><strong>Update GBIF</strong> (separate switch): may review matches and records and start imports (the <strong>Import from GBIF</strong> buttons on the Species list and species pages). Give it only to people who curate the data – Admins included, if they import.</li>
</ul>
<h3>Common tasks</h3>
<ol>
    <li><strong>New user</strong>: fill in name, e-mail, role and a password of at least 10 characters.</li>
    <li><strong>Reset password</strong>: set a new one and tell the person privately.</li>
    <li><strong>Disable</strong> instead of deleting: the person can no longer log in here, but their history is kept. You can enable them again.</li>
</ol>
<p><em>You cannot remove your own Admin role or disable yourself. Disabling here does not block the old /admin. Every change is recorded in History.</em></p>
