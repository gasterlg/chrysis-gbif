<p>The complete diary of the tool: logins, match decisions, rollbacks, approvals, imports, exports and user changes – who did what, and when.</p>
<h3>How to use it</h3>
<ol>
    <li>Choose a <strong>category</strong> (e.g. Match or Users) and a date range.</li>
    <li>Search for a user name or a species ID.</li>
    <li>Click a species target to open its page.</li>
    <li><strong>Export CSV</strong> saves the filtered list, e.g. for a yearly report.</li>
</ol>
<p><em>Times are in UTC (Manila is UTC+8). Entries cannot be edited or deleted.</em></p>
