<p>This is the starting point of the GBIF tool for chrysis.net. It links our species list (the <em>_specie</em> table) to GBIF, the Global Biodiversity Information Facility, and lets you review GBIF records before they are used.</p>
<h3>What you see</h3>
<ul>
    <li>How many species are linked to a GBIF name, and how many are not.</li>
    <li>The last import and how many records are waiting for review.</li>
</ul>
<h3>What to do</h3>
<ol>
    <li>If species are <strong>not matched</strong>, start with <strong>Match review</strong>.</li>
    <li>If records are <strong>pending</strong>, go to <strong>Import review</strong>.</li>
    <li>Otherwise, browse <strong>Species</strong> to check maps or import new records.</li>
</ol>
<p><em>Review pages are visible only to accounts with the “update GBIF” permission.</em></p>
