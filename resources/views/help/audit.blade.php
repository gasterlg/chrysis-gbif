<p>Every login, logout and failed login attempt, with time, account and IP address.</p>
<h3>What to look for</h3>
<ol>
    <li>Filter on <strong>failed</strong> logins.</li>
    <li>Many failures for one account or from one IP can mean someone is guessing passwords: reset that password or disable the account in <strong>Users</strong>.</li>
    <li>After 5 failed attempts in a minute, the login is blocked briefly anyway.</li>
</ol>
