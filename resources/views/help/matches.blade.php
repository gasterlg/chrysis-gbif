<p>Each species in our catalogue must be linked to the right GBIF name, otherwise imports fetch the wrong records. Here the tool proposes a GBIF name for every species and you decide.</p>
<h3>Step by step</h3>
<ol>
    <li>Start with <strong>failed</strong> or <strong>changed</strong> proposals (filters at the top).</li>
    <li>Click <strong>Review…</strong>: compare our name with GBIF’s, its rank, status and confidence.</li>
    <li><strong>Accept</strong> if it is the same taxon. <strong>Reject</strong> if it is wrong – the current link stays as it is.</li>
    <li>If GBIF lists <strong>alternatives</strong>, pick the right one instead.</li>
    <li>If none fits, type a <strong>manual GBIF key</strong> (the number in the gbif.org/species/… address). The tool checks it first.</li>
</ol>
<h3>Good to know</h3>
<ul>
    <li><strong>Synonym</strong>: GBIF knows the name but treats it as a synonym; the proposal uses GBIF’s accepted name. Check it yourself – GBIF’s backbone can be wrong (e.g. a <em>Cleptes</em> name resolved to a chalcid genus). That is why synonyms are <strong>never bulk-accepted</strong>.</li>
    <li><strong>Bulk accept</strong> only takes exact, accepted names with confidence 95 or higher.</li>
    <li><strong>Genus only</strong> (higher rank): GBIF does not know the species, only the genus. Accepting it would import the whole genus, so leave the species unmatched or enter a manual key.</li>
    <li>Every decision is recorded and can be undone in <strong>Changes</strong>.</li>
</ul>
