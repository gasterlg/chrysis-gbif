<ol class="mt-2">
    <li><strong>Match review</strong> – check that every species points to the right GBIF name. Accept good proposals, fix the odd ones.</li>
    <li><strong>Import</strong> – on a species page press <em>Import from GBIF</em> (or ask the developer to run a full import).</li>
    <li><strong>Import review</strong> – look at flagged records first, then approve the good ones and reject mistakes.</li>
    <li><strong>Check</strong> the species map; use <strong>Changes</strong> to undo a wrong match decision.</li>
    <li><strong>Export</strong> approved records with their citation when you need them.</li>
</ol>
<p class="mt-2 text-xs text-slate-500">Nothing runs automatically: imports only happen when someone starts them.</p>
