<p>Download the <strong>approved</strong> GBIF records, for one species or for all, e.g. for a paper or a distribution map.</p>
<h3>Step by step</h3>
<ol>
    <li>Pick a species, or leave “All species”.</li>
    <li>Press <strong>Download zip</strong>. It contains the records (occurrences.csv), the list of source datasets (datasets.csv) and <strong>CITATION.txt</strong>.</li>
</ol>
<h3>Citing and licences</h3>
<ul>
    <li>GBIF data must be <strong>cited</strong>: use CITATION.txt, which lists every source dataset with its DOI.</li>
    <li>Each dataset has a <strong>licence</strong>. <strong>CC0</strong>: free use. <strong>CC BY</strong>: free use with credit. <strong>CC BY-NC</strong>: credit, and <strong>no commercial use</strong>.</li>
    <li>For a publication, a <strong>GBIF download DOI</strong> is best. That option appears here once a GBIF.org account is configured.</li>
</ul>
