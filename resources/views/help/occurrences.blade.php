<p>Records imported from GBIF (with the <strong>Import from GBIF</strong> button on the Species list or on a species’ page – needs the Update GBIF permission, granted by an Admin in Users) wait here until you check them. <strong>Nothing reaches the website until it is approved.</strong></p>
<h3>Step by step</h3>
<ol>
    <li>Filter by species, country or dataset to work in small batches.</li>
    <li>Look at <strong>flagged</strong> records first (filter “Flagged”).</li>
    <li>Tick the good records and choose <strong>Approve</strong>; tick the bad ones and choose <strong>Reject</strong>.</li>
    <li>Open a record to see all details and the link to the original on gbif.org.</li>
</ol>
<h3>What the flags mean</h3>
<ul>
    <li><strong>Far from range</strong>: the point is much further (over 1,500 km, or 4× the usual distance) from the species’ other records. Often wrong coordinates or a misidentification – but it can also be a real new record.</li>
    <li><strong>Rare country</strong>: only one or two records from that country for a well-recorded species. Check the identifier and the collection.</li>
    <li>Flags are hints, not verdicts: you decide.</li>
</ul>
<p><em>If GBIF later changes an approved record, it comes back here as “changed” for a new check.</em></p>
