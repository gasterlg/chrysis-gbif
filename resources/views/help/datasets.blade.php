<p>The GBIF datasets (museum collections, surveys, citizen-science platforms) our imported records come from.</p>
<h3>What you see</h3>
<ul>
    <li>The cards at the top highlight collections of special interest: <strong>NHM London</strong> and <strong>Lund</strong> – with record, type-specimen and image counts.</li>
    <li>The table lists every dataset with how many records, species and approved records it holds, its licence and DOI.</li>
</ul>
<h3>How to use it</h3>
<ol>
    <li>Sort by <strong>Records</strong> to see the main sources.</li>
    <li>Filter by <strong>licence</strong> to find data you may reuse freely (CC0).</li>
    <li>Click a title to open the dataset on gbif.org.</li>
</ol>
