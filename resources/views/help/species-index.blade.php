<p>All species of the chrysis.net catalogue, with their link to GBIF and how many GBIF records we hold.</p>
<h3>How to use it</h3>
<ol>
    <li>Type in the search box: genus, species or subspecies (e.g. <em>Chrysis ignita</em>).</li>
    <li>Use the filters to show, for example, only species <strong>without a GBIF match</strong>.</li>
    <li>Click a column title to sort; click a species name to open its page.</li>
    <li><strong>Export CSV</strong> downloads the list exactly as filtered.</li>
</ol>
<h3>Status colours</h3>
<ul>
    <li><strong>Green</strong>: linked to an exact GBIF name.</li>
    <li><strong>Amber</strong>: linked, but worth a look (synonym, fuzzy or genus-only match).</li>
    <li><strong>Red</strong>: no GBIF match yet – fix it in Match review.</li>
</ul>
